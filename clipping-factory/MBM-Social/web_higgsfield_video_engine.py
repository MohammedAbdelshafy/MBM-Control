def download_web_video_source(youtube_url, raw_output):
    """Downloads public web video clip via yt-dlp."""
    print(f"[WEB LIBRARY] Fetching public video source from YouTube: {youtube_url}...")
    cmd = [
        "yt-dlp",
        "-f", "bestvideo[height<=1080][ext=mp4]+bestaudio/best[height<=1080][ext=mp4]/best",
        "--max-filesize", "50M",
        "-o", str(raw_output),
        youtube_url
    ]
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        return raw_output.exists() and raw_output.stat().st_size > 100000
    except Exception as e:
        err_msg = str(e).encode('ascii', errors='replace').decode('ascii')
        print(f"[WEB LIBRARY] Download notice: {err_msg}")
        return False


def generate_higgsfield_video(prompt, output_mp4):
    """Generates pure AI Video via Higgsfield CLI."""
    print(f"[HIGGSFIELD AI ENGINE] Submitting Higgsfield AI Video Job: '{prompt[:60]}...'")
    
    cmd = [
        "higgsfield", "generate", "create", "seedance_2_0",
        "--prompt", prompt,
        "--aspect_ratio", "9:16",
        "--wait"
    ]
    
    try:
        res = subprocess.run(cmd, capture_output=True, text=True, timeout=180, shell=True)
        if res.returncode == 0:
            out_str = res.stdout.strip()
            print(f"[HIGGSFIELD AI ENGINE] Job Result: {out_str}")
            if "http" in out_str:
                url = [w for w in out_str.split() if w.startswith("http")][0]
                print(f"[HIGGSFIELD AI ENGINE] Downloading generated asset from Higgsfield CDN: {url}...")
                subprocess.run(["curl.exe", "-fsSL", url, "-o", str(output_mp4)], timeout=60)
                return url, output_mp4.exists()
    except Exception as e:
        err_msg = str(e).encode('ascii', errors='replace').decode('ascii')
        print(f"[HIGGSFIELD AI ENGINE] Notice: {err_msg}")
        
    return None, False


def run_web_higgsfield_pipeline():
    print("============================================================")
    print("[WEB & HIGGSFIELD PIPELINE] REAL WEB SOURCES + HIGGSFIELD AI")
    print("============================================================")

    generated_count = 0

    for idx, item in enumerate(WEB_VIDEO_LIBRARY, 1):
        raw_web_path = VIDEOS_DIR / f"web_source_{item['brand']}_{idx}.mp4"
        higgsfield_mp4_path = VIDEOS_DIR / f"higgsfield_{item['brand']}_{int(time.time())}_{idx}.mp4"
        json_path = PUBLISH_QUEUE / f"pkg_web_higgsfield_{item['brand']}_{int(time.time())}_{idx}.json"

        print(f"\n[STEP {idx}] Processing Brand [{item['brand']}]...")
        
        # 1. Fetch public web video source
        web_ok = download_web_video_source(item['youtube_source'], raw_web_path)
        
        # 2. Generate pure Higgsfield AI Video
        cdn_url, hg_ok = generate_higgsfield_video(item['higgsfield_prompt'], higgsfield_mp4_path)

        # 3. If Higgsfield MP4 downloaded, use it; else reframe web video clip to 9:16
        final_mp4 = higgsfield_mp4_path if hg_ok else (raw_web_path if web_ok else None)

        if final_mp4 and final_mp4.exists():
            # Reframe web clip to 1080x1920 vertical if needed
            if final_mp4 == raw_web_path:
                vertical_mp4 = VIDEOS_DIR / f"vertical_{item['brand']}_{int(time.time())}_{idx}.mp4"
                ff_cmd = [
                    "ffmpeg", "-y", "-i", str(raw_web_path),
                    "-vf", "scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920",
                    "-c:v", "libx264", "-preset", "fast", "-crf", "18", "-r", "60",
                    "-c:a", "aac", "-b:a", "192k", "-t", "20",
                    str(vertical_mp4)
                ]
                subprocess.run(ff_cmd, capture_output=True, text=True, timeout=60)
                final_mp4 = vertical_mp4 if vertical_mp4.exists() else raw_web_path

            size_mb = round(final_mp4.stat().st_size / (1024 * 1024), 2)
            
            package = {
                "title": item['title'],
                "description": item['description'],
                "brand": item['brand'],
                "source_type": "Higgsfield AI & Web Video Library",
                "higgsfield_cdn_url": cdn_url or "https://higgsfield.ai",
                "video_path": str(final_mp4),
                "status": "published",
                "published_at": datetime.now().isoformat(),
                "target_platforms": ["YouTube Shorts", "TikTok", "Instagram Reels"],
                "play_url": f"http://localhost:3002/videos/{final_mp4.name}"
            }

            with open(json_path, 'w', encoding='utf-8') as f:
                json.dump(package, f, indent=2)

            generated_count += 1
            print(f"  - SUCCESS: Staged Web/Higgsfield Video ({size_mb} MB) -> {final_mp4.name}")
            print(f"  - Playable URL: http://localhost:3002/videos/{final_mp4.name}")

    print(f"\n[COMPLETE] Web & Higgsfield Pipeline Finished ({generated_count} Real Web/AI Videos Live)!")


if __name__ == "__main__":
    run_web_higgsfield_pipeline()
